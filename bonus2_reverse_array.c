// なぜダメか説明し、正しく直せ。

// 回答：i を unsigned int にすると 0の次に大きな正の数になるため無限ループになる。また、その大きな値を arr[i] に使うことで配列外参照が起きる。
    // i を int に変更すれば、0 の次に -1 になってループを終了できる。
#include <stdio.h>

int main(void) {
    int arr[5] = {10, 20, 30, 40, 50};
    for (int i = 4; i >= 0; i--) {
        printf("%d\n", arr[i]);
    }
}
