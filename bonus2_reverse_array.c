#include <stdio.h>

int main(void) {
    unsigned int arr[5] = {10, 20, 30, 40, 50};
    for (unsigned int i = 4; 5 > i; i--) {
        printf("%d\n", arr[i]);
    }
}

/*説明
i >= 0にすると、0のときに-1されて、大きな数に戻ってしまう。つまりずっと真数になってしまう。
実行はできるものの、コード自体は再生されていて、配列の中を探し続けている（一応、箱の数が5つしかないのでそこのみ実行される）
正しくは、下限を設定するのではなく上限を設定する。つまり5 > iにするとうまくいく。
*/