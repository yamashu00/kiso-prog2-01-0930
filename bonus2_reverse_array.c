//----------説明-----------
// i は unsigned int なので、0 から i-- すると大きな値に戻る。
// そのため i >= 0 は常に真になり、無限ループと配列外参照が起きる。
// 添字を int にすれば、i が -1 になった時点でループを終了できる。
//------------------------

#include <stdio.h>

int main(void)
{
    unsigned int arr[5] = {10, 20, 30, 40, 50};
    for (int i = 4; i >= 0; i--)
    {
        printf("%u\n", arr[i]);
    }
}
